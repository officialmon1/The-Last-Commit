// Leaderboard for Lenny's Last Commit, deployed as a Neon Function next to the leaderboard database.
//   GET  /            -> { entries: [{ name, seconds, created_at }, ...] }   the ten fastest escapes
//   POST / {name, seconds} -> { entries: [...], rank }                        adds an escape, returns its rank
// The game only knows this function's public URL; the database credentials stay here (Neon injects DATABASE_URL).
// No dependencies: queries go through Neon's HTTP SQL endpoint with fetch, so the file deploys as-is (--no-bundle).

const TOP = 10;
const MAX_NAME = 20;
const MAX_SECONDS = 36 * 60;   // the whole run is capped by the game's 36-minute clock

const headers = {
  'content-type': 'application/json',
  'access-control-allow-origin': '*',
  'access-control-allow-methods': 'GET, POST, OPTIONS',
  'access-control-allow-headers': 'content-type',
};
const json = (body, status = 200) => new Response(JSON.stringify(body), { status, headers });

async function sql(query, params = []) {
  const conn = process.env.DATABASE_URL_UNPOOLED || process.env.DATABASE_URL;
  if (!conn) throw new Error('DATABASE_URL is not set on this branch');
  const host = new URL(conn).hostname;
  const r = await fetch(`https://${host}/sql`, {
    method: 'POST',
    headers: { 'Neon-Connection-String': conn, 'Neon-Array-Mode': 'false', 'content-type': 'application/json' },
    body: JSON.stringify({ query, params }),
  });
  const data = await r.json();
  if (!r.ok) throw new Error(data.message || `SQL request failed (${r.status})`);
  return data.rows;
}

let ready;
function ensureTable() {
  ready ??= sql(`CREATE TABLE IF NOT EXISTS leaderboard (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name text NOT NULL,
      seconds integer NOT NULL CHECK (seconds > 0),
      created_at timestamptz NOT NULL DEFAULT now())`).catch((e) => { ready = undefined; throw e; });
  return ready;
}

const top = () => sql(`SELECT name, seconds, created_at FROM leaderboard ORDER BY seconds ASC, created_at ASC LIMIT ${TOP}`);

export default {
  async fetch(request) {
    if (request.method === 'OPTIONS') return new Response(null, { status: 204, headers });
    try {
      await ensureTable();
      if (request.method === 'GET') return json({ entries: await top(), rank: 0 });
      if (request.method === 'POST') {
        let body;
        try { body = await request.json(); } catch { return json({ error: 'expected a JSON body' }, 400); }
        const name = String(body?.name ?? '').trim().slice(0, MAX_NAME);
        const seconds = Math.round(Number(body?.seconds));
        if (!name) return json({ error: 'name is required' }, 400);
        if (!Number.isFinite(seconds) || seconds <= 0 || seconds > MAX_SECONDS) return json({ error: `seconds must be between 1 and ${MAX_SECONDS}` }, 400);
        await sql('INSERT INTO leaderboard (name, seconds) VALUES ($1, $2)', [name, seconds]);
        const [{ rank }] = await sql('SELECT count(*)::int + 1 AS rank FROM leaderboard WHERE seconds < $1', [seconds]);
        return json({ entries: await top(), rank: Number(rank) });
      }
      return json({ error: 'method not allowed' }, 405);
    } catch (e) {
      return json({ error: String(e?.message ?? e) }, 500);
    }
  },
};
